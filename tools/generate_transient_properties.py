"""Generate pystemd/systemd1/transient_properties.py from the probe results
in tools/transient-properties/ (see probe_transient_properties.py).

    python3 tools/generate_transient_properties.py          # write the module
    python3 tools/generate_transient_properties.py --check  # fail if stale
"""

from __future__ import annotations

import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "tools", "transient-properties")
MODULE = os.path.join(ROOT, "pystemd", "systemd1", "transient_properties.py")

HEADER = '''\
#
# This source code is licensed under the license found in the LICENSE file in
# the root directory of this source tree.
#
# Generated by tools/generate_transient_properties.py from probing
# {versions}. Do not edit by hand.
#

"""D-Bus signatures systemd accepts when setting properties of transient
units (StartTransientUnit, SetUnitProperties).

These are measured, not copied from the introspection XML: the type a property
is set with often differs from the type it is read as (ExecStart is read as
a(sasbttttuii) but set as a(sasb)), and some properties are write-only.

A comment lists the probed systemd versions a property is settable on when
that is not all of them.
"""

TRANSIENT_PROPERTY_SIGNATURES: dict[bytes, bytes] = {{
'''


def load():
    results = []
    for path in glob.glob(os.path.join(DATA, "systemd-*.json")):
        with open(path) as f:
            result = json.load(f)
        version = int(re.search(r"systemd (\d+)", result["systemd"]).group(1))
        results.append((version, result))
    return sorted(results, key=lambda r: r[0])


def generate():
    results = load()
    versions = [v for v, _ in results]
    signatures = {}
    settable_on = {}
    for version, result in results:
        for name, sig in result["properties"].items():
            if signatures.setdefault(name, sig) != sig:
                raise SystemExit(
                    f"{name}: signature {signatures[name]} vs {sig} on {version}"
                )
            settable_on.setdefault(name, []).append(version)

    out = [
        HEADER.format(
            versions=", ".join(f"systemd {v}" for v in versions[:-1])
            + f" and systemd {versions[-1]}"
        )
    ]
    for name in sorted(signatures):
        line = f'    b"{name}": b"{signatures[name]}",'
        if settable_on[name] != versions:
            notes = [", ".join(map(str, settable_on[name]))]
            ignored = [v for v, r in results if name in r.get("ignored", [])]
            if ignored:
                notes.append("ignored on " + ", ".join(map(str, ignored)))
            line += "  # " + "; ".join(notes)
        out.append(line + "\n")
    out.append("}\n")
    return "".join(out)


def main():
    code = generate()
    if sys.argv[1:] == ["--check"]:
        with open(MODULE) as f:
            if f.read() != code:
                sys.exit(f"{MODULE} is stale, run {sys.argv[0]}")
        return
    with open(MODULE, "w") as f:
        f.write(code)


if __name__ == "__main__":
    main()
